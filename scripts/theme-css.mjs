#!/usr/bin/env node
// Generates the per-theme block at the end of stylesheet.css from
// services/themes.js. Run `node scripts/theme-css.mjs` after editing a palette;
// tests/appearance.test.mjs fails while the stylesheet is out of date.
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {THEMES, TEXT} from '../services/themes.js';

export const BEGIN = '/* ---- Theme palettes (generated by scripts/theme-css.mjs; do not edit) ---- */';
export const END = '/* ---- End of generated theme palettes ---- */';

const rgba = (rgb, alpha) => `rgba(${rgb.join(',')},${alpha})`;

export function themeBlock(theme) {
    const T = `.ubuntu-island-theme-${theme.id}`;
    const sel = (...names) => names.map(name => `${T} ${name}`).join(', ');
    const accent = theme.accent, surface = theme.surface;
    const checked = [1, 3, 5].map(i => parseInt(accent.slice(i, i + 2), 16));
    return [
        `/* ${theme.label} */`,
        // Detached popups carry the theme class themselves, not on an ancestor.
        `${T}.ubuntu-island-date-tooltip { color: ${TEXT}; background-color: ${rgba(theme.bottom, 1)}; ` +
            `background-gradient-direction: vertical; background-gradient-start: ${rgba(theme.top, 1)}; ` +
            `background-gradient-end: ${rgba(theme.bottom, 1)}; border-color: ${rgba(theme.edge, 0.2)}; }`,
        `${T}.ubuntu-island-calendar-day-tooltip { color: ${theme.secondary}; }`,
        `${sel('.ubuntu-island-muted', '.ubuntu-island-metric-name', '.ubuntu-island-metric-sub',
            '.ubuntu-island-artist', '.ubuntu-island-source', '.ubuntu-island-time', '.ubuntu-island-device-status',
            '.ubuntu-island-tab')} { color: ${theme.secondary}; }`,
        `${sel('.ubuntu-island-header', '.ubuntu-island-agent-heading')} { color: ${theme.heading}; }`,
        `${sel('.ubuntu-island-metric', '.ubuntu-island-output', '.ubuntu-island-device-button', '.ubuntu-island-calendar-event')} ` +
            `{ background-color: ${rgba(surface, 0.06)}; border-color: ${rgba(surface, 0.11)}; }`,
        `${sel('.ubuntu-island-output:hover', '.ubuntu-island-device-button:hover', '.ubuntu-island-calendar-event:hover',
            '.ubuntu-island-ghost:hover', '.ubuntu-island-calendar-day:hover .ubuntu-island-calendar-date',
            '.ubuntu-island-agent-row:hover', '.ubuntu-island-notification-chip:hover')} { background-color: ${rgba(surface, 0.12)}; }`,
        `${sel('.ubuntu-island-output:active', '.ubuntu-island-device-button:active', '.ubuntu-island-ghost:active',
            '.ubuntu-island-calendar-event:active')} { background-color: ${rgba(surface, 0.18)}; }`,
        // Keyboard focus rings keep each base width and form; only the colour is themed.
        `${sel('.ubuntu-island-output:focus', '.ubuntu-island-device-button:focus', '.ubuntu-island-ghost:focus',
            '.ubuntu-island-seal:focus', '.ubuntu-island-media-mode:focus', '.ubuntu-island-media-text-button:focus',
            '.ubuntu-island-media-seek:focus', '.ubuntu-island-player-picker:focus', '.ubuntu-island-notification-open:focus')} { box-shadow: inset 0 0 0 2px ${theme.focus}; }`,
        `${sel('.ubuntu-island-calendar-control:focus', '.ubuntu-island-output-mode:focus', '.ubuntu-island-title-toggle:focus',
            '.ubuntu-island-agent-session:focus', '.ubuntu-island-agent-button:focus', '.ubuntu-island-agent-menu-button:focus',
            '.ubuntu-island-notification-chip:focus')} ` +
            `{ box-shadow: inset 0 0 0 1px ${theme.focus}; }`,
        `${sel('.ubuntu-island-calendar-event:focus', '.ubuntu-island-agent-composer:focus', '.ubuntu-island-agent-prompt:focus',
            '.ubuntu-island-agent-entry:focus', '.ubuntu-island-quick-ask-entry:focus')} { border-color: ${theme.focus}; }`,
        // Tinted navigation bar: constant alpha, independent of the opacity setting.
        `${sel('.ubuntu-island-navigation')} { background-color: ${rgba(theme.bottom, 0.32)}; border-color: ${rgba(checked, 0.24)}; }`,
        `${sel('.ubuntu-island-navigation .ubuntu-island-navigation-caption')} { color: ${accent}; }`,
        `${sel('.ubuntu-island-calendar-month')} { border-color: ${rgba(surface, 0.11)}; }`,
        // Notification rows: hairline separators and a soft hover, no boxes.
        `${sel('.ubuntu-island-notification')} { border-color: ${rgba(surface, 0.09)}; }`,
        `${sel('.ubuntu-island-notification-card:hover')} { background-color: ${rgba(surface, 0.08)}; }`,
        `${sel('.ubuntu-island-history')} { color: ${theme.history}; }`,
        `${sel('.ubuntu-island-network-down')} { color: ${theme.chartDown}; }`,
        `${sel('.ubuntu-island-network-up')} { color: ${theme.chartUp}; }`,
        `${sel('.ubuntu-island-history-network')} { -ubuntu-island-chart-down: ${theme.chartDown}; ` +
            `-ubuntu-island-chart-up: ${theme.chartUp}; }`,
        `${sel('.ubuntu-island-seal', '.ubuntu-island-agent-primary', '.ubuntu-island-quick-ask-send')} { background-color: ${theme.strong}; }`,
        `${sel('.ubuntu-island-seal')} { border-color: ${rgba(surface, 0.26)}; }`,
        `${sel('.ubuntu-island-seal:hover', '.ubuntu-island-agent-primary:hover', '.ubuntu-island-agent-primary:focus',
            '.ubuntu-island-quick-ask-send:hover')} { background-color: ${theme.strongHover}; }`,
        `${sel('.ubuntu-island-seal:active', '.ubuntu-island-agent-primary:active')} { background-color: ${theme.strongPressed}; }`,
        `${sel('.slider')} { -barlevel-active-background-color: ${accent}; -barlevel-overdrive-color: ${accent}; }`,
        `${sel('.ubuntu-island-output-active')} { background-color: ${rgba(checked, 0.20)}; border-color: ${accent}; }`,
        `${sel('.ubuntu-island-media-mode:checked', '.ubuntu-island-media-text-button:checked', '.ubuntu-island-notification-chip:checked',
            '.ubuntu-island-notification-dnd:checked', '.ubuntu-island-notification-new')} ` +
            `{ color: ${accent}; background-color: ${rgba(checked, 0.16)}; }`,
        `${sel('.ubuntu-island-calendar-today .ubuntu-island-calendar-date')} ` +
            `{ background-color: ${theme.strong}; border-color: ${theme.todayBorder}; }`,
        // Tabs: the sliding marker shows the selection, so the selected tab's own
        // marker stays clear, even when focused: otherwise it appears under the new
        // tab before the slider arrives. Order matters at equal specificity: selected
        // after hover, focus after selected (focus markers on other tabs stay
        // visible), focused-selected last. The focused glyph still turns light.
        `${sel('.ubuntu-island-notification-dot')} { background-color: ${accent}; }`,
        `${sel('.ubuntu-island-tab-slider')} { background-color: ${theme.marker}; }`,
        `${sel('.ubuntu-island-tab:hover', '.ubuntu-island-tab:focus')} { color: #f4f6f9; }`,
        `${sel('.ubuntu-island-tab-selected')} { color: ${accent}; }`,
        `${sel('.ubuntu-island-tab-selected .ubuntu-island-tab-marker')} { background-color: transparent; }`,
        `${sel('.ubuntu-island-tab:focus .ubuntu-island-tab-marker')} { background-color: ${theme.focus}; }`,
        `${sel('.ubuntu-island-tab-selected:focus .ubuntu-island-tab-marker')} { background-color: transparent; }`,
        // Theme fills above outrank the base :disabled rules; restore them.
        `${sel('.ubuntu-island-seal:disabled', '.ubuntu-island-device-button:disabled')} { color: #9a8c82; background-color: #363940; }`,
        `${sel('.ubuntu-island-quick-ask-send:disabled')} { color: #7d818b; background-color: rgba(220,225,240,0.08); }`,
        `${sel('.ubuntu-island-agent-primary:disabled')} { color: #939aa6; background-color: transparent; }`,
    ].join('\n');
}

export const themeCss = () =>
    `${BEGIN}\n/* Each theme: secondary text, card surfaces, borders, hover/pressed states,\n` +
    `   accent, focus rings, headings, navigation and tab markers. Tints: appearance.js. */\n\n` +
    `${Object.values(THEMES).map(themeBlock).join('\n\n')}\n${END}\n`;

export function generatedRegion(css) {
    const start = css.indexOf(BEGIN), end = css.indexOf(END);
    return start < 0 || end < 0 ? null : css.slice(start, end + END.length + 1);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const path = fileURLToPath(new URL('../stylesheet.css', import.meta.url));
    const css = readFileSync(path, 'utf8');
    const region = generatedRegion(css);
    const next = region === null ? `${css.trimEnd()}\n\n${themeCss()}` : css.replace(region, themeCss());
    writeFileSync(path, next);
    console.log(`Wrote ${Object.keys(THEMES).length} theme palettes to stylesheet.css`);
}
