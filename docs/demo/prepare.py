#!/usr/bin/env python3
"""Normalize private footage and synchronize the editable Remotion timeline."""
import json
import math
from pathlib import Path
import re
import subprocess

root = Path(__file__).resolve().parent
metadata = json.loads((root / 'public/capture.json').read_text())
probe = subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration',
                                 '-of', 'json', str(root / 'public/tour.raw.mp4')], text=True)
raw_duration = float(json.loads(probe)['format']['duration'])
motion = metadata.get('motion', [])
for index, item in enumerate(motion):
    assert 0 <= item['start'] < item['end'] <= raw_duration + 0.1
    assert item['speed'] > 0
    if index:
        assert motion[index - 1]['end'] <= item['start']


def retime(seconds):
    return seconds - sum((1 - 1 / item['speed']) *
                         min(max(seconds - item['start'], 0), item['end'] - item['start'])
                         for item in motion)

duration = math.ceil(retime(raw_duration) + 1)
# Preserve real compositor frames. No optical-flow synthesis: slowed native
# transitions are restored to presentation speed before the final 60fps sampling.
savings = '+'.join(f"{1 - 1 / item['speed']:.9f}*clip(T-{item['start']:.6f},0,{item['end'] - item['start']:.6f})"
                   for item in motion) or '0'
filters = f"setpts='PTS-STARTPTS-({savings})/TB',fps=60,tpad=stop_mode=clone:stop_duration=2"
subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y',
                '-i', str(root / 'public/tour.raw.mp4'), '-vf', filters,
                '-t', str(duration), '-c:v', 'libx264', '-crf', '17', '-preset', 'veryfast',
                '-pix_fmt', 'yuv420p', '-threads', '2', '-an', '-movflags', '+faststart',
                str(root / 'public/tour.mp4')], check=True)
for item in metadata['chapters'] + metadata['preferences']:
    item['at'] = retime(item['at'])
metadata['cues'] = {key: retime(value) for key, value in metadata['cues'].items()}
# Report real capture density over the moving portion, excluding the settle hold.
frame_probe = json.loads(subprocess.check_output(['ffprobe', '-v', 'error', '-show_frames',
    '-show_entries', 'frame=best_effort_timestamp_time', '-of', 'json',
    str(root / 'public/tour.raw.mp4')], text=True))
timestamps = [float(frame['best_effort_timestamp_time']) for frame in frame_probe['frames']]
for item in motion:
    moving_end = item['start'] + (0.5 if item['kind'] == 'expand' else 0.375) * item.get('captureScale', 3)
    count = sum(item['start'] <= timestamp < moving_end for timestamp in timestamps)
    output_seconds = (moving_end - item['start']) / item['speed']
    print(f"{item['kind']}: {count} captured frames across {output_seconds:.2f}s of final motion "
          f"({count / output_seconds:.1f} source frames per output second)", flush=True)
starts = [round(chapter['at'] * 60) for chapter in metadata['chapters']] + [duration * 60]
composition = root / 'src/Composition.tsx'
text = composition.read_text()
pattern = r'<Sequence name="([^"]+)"(?: from=\{\d+\})? durationInFrames=\{\d+\}>'
matches = list(re.finditer(pattern, text))
if len(matches) != len(metadata['chapters']):
    raise RuntimeError('Caption scenes no longer match the capture chapters')
for i, match in reversed(list(enumerate(matches))):
    if match[1] != metadata['chapters'][i]['name']:
        raise RuntimeError(f'Caption order mismatch: {match[1]}')
    start = f' from={{{starts[i]}}}' if starts[i] else ''
    replacement = f'<Sequence name="{match[1]}"{start} durationInFrames={{{starts[i+1] - starts[i]}}}>'
    text = text[:match.start()] + replacement + text[match.end():]
composition.write_text(text)
registration = root / 'src/Root.tsx'
registration.write_text(re.sub(r'durationInFrames=\{\d+\}',
                              f'durationInFrames={{{duration * 60}}}', registration.read_text()))
chapters = {item['name']: round(item['at'] * 60) for item in metadata['chapters']}
timing = {'chapters': chapters, 'cues': {key: round(value * 60) for key, value in metadata['cues'].items()},
          'preferences': [{**item, 'at': round(item['at'] * 60)} for item in metadata['preferences']]}
(root / 'src/recording.ts').write_text('// Generated by prepare.py from private capture timestamps.\nexport const recording = ' + json.dumps(timing, indent=2) + ';\n')
print(f'Prepared {duration}s at 60fps; {len(matches)} caption scenes.')
